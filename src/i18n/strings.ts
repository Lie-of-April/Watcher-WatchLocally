export function t(key: string, vars?: Vars): string {
  let s = STRINGS[key]
  if (s == null) return key
  if (vars) {
    for (const k in vars) {
      s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), String(vars[k]))
    }
  }
  return s
}

export default t
